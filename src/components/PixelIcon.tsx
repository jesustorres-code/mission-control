type Props = { name: IconName; size?: number; color?: string; className?: string };

export default function PixelIcon({ name, size = 16, color = 'currentColor', className = '' }: Props) {
  const grid = grids[name];
  return (
    <svg width={size} height={size} viewBox="0 0 8 8" className={`pixelated ${className}`} aria-hidden>
      {grid.map((row, y) =>
        row.map((cell, x) =>
          cell ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={color} /> : null
        )
      )}
    </svg>
  );
}
